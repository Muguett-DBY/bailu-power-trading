func TestHandbookAnswersTradingQuestions(t *testing.T) {
	book := loadHandbook(t)
	for _, c := range handbookQuestions {
		found := book.search(c.question, 3, relevance)
		titles := make([]string, len(found))
		for i, section := range found {
			titles[i] = section.Title
		}
		if !slices.ContainsFunc(strings.Split(c.topic, "|"), func(topic string) bool { return slices.Contains(titles, topic) }) {
			t.Errorf("%q did not bring up %q; it brought up %q", c.question, c.topic, titles)
		}
	}
}

// The same for the national spot-market rule, as a project folder holds it:
// a question about a provision has to bring up that provision first, and one
// about a passage has to bring it up among the first three.
func TestDocumentRetrievalFindsTheProvision(t *testing.T) {
	pdf := filepath.Join("testdata", "spot-rule-1217.pdf")
	pages, err := extractDoc(pdf)
	if err != nil {
		t.Fatal(err)
	}
	chunks := chunkDocuments("电力现货市场基本规则（试行）.pdf", pages)
	for _, c := range []struct{ question, article string }{
		{"报价限价不应超过出清限价范围，是第几条的要求", "第三十八条"},
		{"经营主体在结算中的权利和义务是什么", "第九十条"},
	} {
		hits := searchChunks(chunks, c.question, 3, relevance)
		if len(hits) == 0 || hits[0].Article != c.article {
			t.Errorf("%q: the first passage is not %s", c.question, c.article)
		}
	}
	// What a term means is in the entry of the glossary that opens with it.
	for _, c := range []struct{ question, phrase string }{
		{"日前市场是什么意思", "运行日提前一天"},
		{"节点边际电价是什么", "Locational Marginal Price"},
		{"市场限价是什么意思", "市场运行允许出现的价格范围"},
	} {
		hits := searchChunks(chunks, c.question, 3, relevance)
		if len(hits) == 0 || !strings.Contains(hits[0].Text, c.phrase) {
			t.Errorf("%q: the first passage does not hold %q", c.question, c.phrase)
		}
	}
	for _, c := range []struct{ question, phrase string }{
		{"市场出清结果应该包括哪些内容", "日前正式出清结果应包含"},
		{"迟报、漏报或者不报的按什么处理", "缺省值"},
	} {
		var found []string
		for _, hit := range searchChunks(chunks, c.question, 3, relevance) {
			found = append(found, hit.Text)
		}
		if !slices.ContainsFunc(found, func(text string) bool { return strings.Contains(text, c.phrase) }) {
			t.Errorf("%q: none of the first three passages contains %q", c.question, c.phrase)
		}
	}
}
